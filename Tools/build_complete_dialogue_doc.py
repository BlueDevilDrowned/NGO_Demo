def add_matrix_table(doc, section, rows, weights, font_size=9.0):
    table = doc.add_table(rows=len(rows), cols=len(weights))
    table.autofit = False
    for row_index, row_data in enumerate(rows):
        for col_index, value in enumerate(row_data):
            cell = table.rows[row_index].cells[col_index]
            cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            p = cell.paragraphs[0]
            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
            run = p.add_run(str(value))
            set_font(
                run,
                size=font_size,
                bold=(row_index == 0),
                color=(255, 255, 255) if row_index == 0 else (55, 62, 66),
            )
            if row_index == 0:
                tc_pr = cell._tc.get_or_add_tcPr()
                shd = OxmlElement("w:shd")
                shd.set(qn("w:fill"), "3B5968")
                tc_pr.append(shd)
    set_repeat_table_header(table.rows[0])
    total_width = section_content_width_dxa(section)
    column_widths = column_widths_from_weights(weights, total_width)
    apply_table_geometry(
        table,
        column_widths,
        cell_margins_dxa={"top": 100, "bottom": 100, "start": 140, "end": 140},
    )
    return table


