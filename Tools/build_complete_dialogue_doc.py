def add_dialogue(doc, lines):
    for speaker, text in lines:
        p = doc.add_paragraph(style="Dialogue Body")
        lead = p.add_run(f"{speaker}：")
        set_font(lead, bold=True, color=(35, 61, 74))
        body = p.add_run(text)
